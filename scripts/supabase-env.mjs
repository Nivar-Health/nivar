#!/usr/bin/env node
// Generates fresh secrets for the local Supabase stack and wires the web app to it.
//   supabase/docker/.env    read by docker compose (git-ignored)
//   apps/web/.env.local     read by Next.js, the seed and the tests (git-ignored)
// Existing files are kept unless --force is passed, so rerunning never breaks a running stack.
import { createHmac, randomBytes } from "node:crypto";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dockerEnv = join(root, "supabase/docker/.env");
const webEnv = join(root, "apps/web/.env.local");
const force = process.argv.includes("--force");

const b64url = (buf) => Buffer.from(buf).toString("base64url");
const secret = (bytes) => randomBytes(bytes).toString("base64url");

/** HS256 JWT for a Supabase API key (anon or service_role), valid for 10 years. */
function apiKey(role, jwtSecret) {
  const now = Math.floor(Date.now() / 1000);
  const header = b64url(JSON.stringify({ alg: "HS256", typ: "JWT" }));
  const payload = b64url(JSON.stringify({ role, iss: "supabase", iat: now, exp: now + 10 * 365 * 24 * 3600 }));
  const sig = createHmac("sha256", jwtSecret).update(`${header}.${payload}`).digest("base64url");
  return `${header}.${payload}.${sig}`;
}

if (existsSync(dockerEnv) && !force) {
  console.log(`Kept existing ${dockerEnv} (pass --force to regenerate, which invalidates all sessions).`);
  process.exit(0);
}

const jwtSecret = secret(48);
const anonKey = apiKey("anon", jwtSecret);
const serviceKey = apiKey("service_role", jwtSecret);
const publicUrl = "http://localhost:8000";

const docker = {
  POSTGRES_PASSWORD: secret(24),
  POSTGRES_HOST_PORT: "54332",
  JWT_SECRET: jwtSecret,
  JWT_EXPIRY: "3600",
  ANON_KEY: anonKey,
  SERVICE_ROLE_KEY: serviceKey,
  SECRET_KEY_BASE: secret(48),
  REALTIME_DB_ENC_KEY: randomBytes(8).toString("hex"),
  PG_META_CRYPTO_KEY: secret(32),
  DASHBOARD_USERNAME: "supabase",
  DASHBOARD_PASSWORD: secret(18),
  SUPABASE_PUBLIC_URL: publicUrl,
  SITE_URL: "http://localhost:3100",
  API_GW_HTTP_PORT: "8000",
};

const web = {
  NEXT_PUBLIC_SUPABASE_URL: publicUrl,
  NEXT_PUBLIC_SUPABASE_ANON_KEY: anonKey,
  SUPABASE_SERVICE_ROLE_KEY: serviceKey,
};

const toEnv = (obj, header) => `${header}\n${Object.entries(obj).map(([k, v]) => `${k}=${v}`).join("\n")}\n`;

mkdirSync(dirname(dockerEnv), { recursive: true });
writeFileSync(dockerEnv, toEnv(docker, "# Generated by scripts/supabase-env.mjs. Local secrets, never commit."), { mode: 0o600 });
writeFileSync(webEnv, toEnv(web, "# Generated by scripts/supabase-env.mjs for the local Supabase stack."), { mode: 0o600 });
console.log(`Wrote ${dockerEnv}`);
console.log(`Wrote ${webEnv}`);
console.log(`Studio (pnpm supabase:studio): ${publicUrl}  user ${docker.DASHBOARD_USERNAME}, password in supabase/docker/.env`);
